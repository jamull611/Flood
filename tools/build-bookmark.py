#!/usr/bin/env python3
"""Rebuilds the AdStrat bookmark files from the adstratParse and adstratGrabber functions in the tracker:
  adstrat-bookmark.js  - run by the short bookmark (loads the latest code each time)
  bookmark.html        - a page showing the full bookmark code, for when the short one is blocked
Run from the repo root after changing either function: python3 tools/build-bookmark.py"""
from urllib.parse import quote
import html

s = open('adjuster-claim-tracker.html').read()
a = s.index('function adstratParse(root) {'); b = s.index('// This function is turned into a bookmark.', a)
c = s.index('function adstratGrabber(parse) {'); d = s.index("const AS_MARK = 'ADSTRAT-CLAIMS v1';", c)
parse, grab = s[a:b].rstrip(), s[c:d].rstrip()

open('adstrat-bookmark.js', 'w').write("""// AdStrat bookmark for the Adjuster Claim Tracker.
// The phone/computer bookmark is a short loader that runs this file on your AdStrat claims page.
// It reads every page of your claims list (read-only) and offers "Copy for tracker".
// GENERATED from adjuster-claim-tracker.html (adstratParse + adstratGrabber) by tools/build-bookmark.py.
// Don't edit by hand: change those functions in the tracker and re-run the script.
(function () {
""" + parse + "\n" + grab + "\nadstratGrabber(adstratParse);\n})();\n")

# Same encoding as the tracker's bookmarkCode (encodeURIComponent).
full = 'javascript:' + quote('(' + grab + ')(' + parse + ')', safe="-_.!~*'()")
open('bookmark.html', 'w').write("""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>AdStrat Bookmark Code</title>
<!-- GENERATED by tools/build-bookmark.py. Don't edit by hand. -->
<style>
  :root { --bg: #fcfbf8; --text: #222; --muted: #666; --accent: #b31f4b; --border: #ddd; }
  @media (prefers-color-scheme: dark) { :root { --bg: #1a1d23; --text: #eee; --muted: #aaa; --border: #444; } }
  body { margin: 0; padding: 16px; background: var(--bg); color: var(--text); font: 16px/1.5 system-ui, sans-serif; max-width: 680px; margin-inline: auto; }
  h1 { font-size: 20px; margin: 0 0 8px; }
  p, li { color: var(--text); }
  .muted { color: var(--muted); font-size: 14px; }
  button { width: 100%; padding: 14px; font: inherit; font-weight: 600; color: #fff; background: var(--accent); border: 0; border-radius: 10px; margin: 8px 0; }
  textarea { width: 100%; box-sizing: border-box; height: 140px; font: 12px monospace; border: 1px solid var(--border); border-radius: 8px; padding: 8px; background: transparent; color: var(--text); }
  #ok { color: #16a34a; font-weight: 600; min-height: 1.5em; }
</style>
</head>
<body>
<h1>AdStrat bookmark: full code</h1>
<p class="muted">Use this if the short bookmark says it "could not load". It's the same code, without loading anything from the internet.</p>
<button id="copy">Copy full bookmark code</button>
<div id="ok"></div>
<p class="muted">If Copy doesn't work: tap inside the box, Select all, then Copy.</p>
<textarea id="code" readonly>""" + html.escape(full) + """</textarea>
<ol>
  <li>Copy the code above.</li>
  <li>Edit your <b>Copy AdStrat claims</b> bookmark: delete its address and paste this code. Check it starts with <b>javascript:</b>.</li>
  <li>On your AdStrat claims list, tap the bookmark, then <b>Copy for tracker</b>.</li>
  <li>In the tracker: <b>Claims → ⟳ Sync from AdStrat</b>.</li>
</ol>
<p class="muted">This page changes when the bookmark is updated. If the short bookmark works for you, you never need it.</p>
<script>
  const box = document.getElementById('code'), ok = document.getElementById('ok');
  document.getElementById('copy').addEventListener('click', async () => {
    try { await navigator.clipboard.writeText(box.value); }
    catch (e) { box.focus(); box.select(); box.setSelectionRange(0, box.value.length); document.execCommand('copy'); }
    ok.textContent = '✓ Copied ' + box.value.length.toLocaleString() + ' characters. Now paste it as the bookmark address.';
  });
</script>
</body>
</html>
""")
print('adstrat-bookmark.js and bookmark.html rebuilt; full code is', len(full), 'characters')
